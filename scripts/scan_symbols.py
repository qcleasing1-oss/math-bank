#      (ยอด "หาย 114" เท่ากันทั้งสองตัวหาร เพราะของที่หายคือ \mathrm ล้วน ๆ
#       ซึ่งไม่ได้อยู่ในไวต์ลิสต์ ⇒ การกลบไม่แตะมันเลย)
