#   = ในซอร์ส .json เขียนไว้เป็น \\\" ⇒ เด็กเห็นเครื่องหมาย \\ คาอยู่กลางประโยค
#   ยาแก้: ใช้อัญประกาศไทย “ ” ⛔ ไม่ใช่ \" ที่ escape ซ้อนชั้น
