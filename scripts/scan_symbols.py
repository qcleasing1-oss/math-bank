#    เลขนั้นจะตอบคนละคำถามกับชื่อของมันทันที = ㊳ ขาที่ห้าเต็ม ๆ
#    ⇒ กงล้อของตัวเอง (escape_questions) · มองเห็นทุกรอบ · ลดได้อย่างเดียว
