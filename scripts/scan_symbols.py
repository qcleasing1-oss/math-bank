def _run_split_cases(fn):
    """คืนรายชื่อเคสที่ล้มเมื่อใช้ fn เป็นตัวแยกถัง"""
    fails = []
    for name, nh, oh, em, ew in SPLIT_CASES:
        try:
            m, w = fn(nh, oh)
            good = sorted(m) == sorted(em) and sorted(w) == sorted(ew)
        except Exception:
            good = False
        if not good:
            fails.append(name)
    return fails


