def check_word_banned(d=WORD_BANNED):
    """คืน (ใช้ได้ไหม, เหตุผลตาย[]) — "เติมคำโดยไม่มีเหตุผล" ต้องล้มตรงนี้ ไม่ใช่ถูกทวงทีหลัง"""
    if not isinstance(d, dict):
        return False, ['WORD_BANNED ต้องเป็น dict {คำ: เหตุผล} '
                       f'— พบชนิด {type(d).__name__} '
                       '(ถ้ากลับไปเป็น list เมื่อไร เหตุผลจะหายไปทั้งรายการ)']
    fatal = []
    for w, why in d.items():
        if not isinstance(w, str) or not w.strip():
            fatal.append(f'คีย์ {w!r} ไม่ใช่คำ')
            continue
        n = len(why.strip()) if isinstance(why, str) else 0
        if n < MIN_WORD_REASON:
            fatal.append(f'{w!r} มีเหตุผลยาว {n} ตัวอักษร — ต้องอย่างน้อย {MIN_WORD_REASON}'
                         ' ⇒ เติมคำได้เฉพาะพร้อมเหตุผล')
    return (not fatal), fatal


def _word_re(w):
    """ขอบคำแบบไม่กัน \\ นำหน้า โดยตั้งใจ
    ⇒ \\cosec ก็ถูกจับด้วย (เป็นสัญกรณ์เดียวกัน และไม่ใช่แมโครจริงของ LaTeX ด้วยซ้ำ)"""
    return re.compile(r'(?<![A-Za-z])' + re.escape(w) + r'(?![A-Za-z])')


WORD_RE = {w: _word_re(w) for w in WORD_BANNED}


def attribute_shell(strings, word):
    """นับว่าจุดที่เจอ "อยู่ในเปลือกไหน" — เพื่อบอกคนแก้ว่าต้องไปแก้ตรงไหน
    ⛔ ไม่มีผลต่อคำตัดสินเลย (ดูข้อพิสูจน์ชั้น (ก)) — ใช้รายงานอย่างเดียว"""
    rx = WORD_RE[word]
    counts = {}
    for s in strings:
        rngs = shell_ranges(s)
        for m in rx.finditer(s):
            names = [sh for sh, a, b in rngs if a <= m.start() < b]
            key = names[-1] if names else 'เปล่า (ไม่มีเปลือก)'
            counts[key] = counts.get(key, 0) + 1
    return counts


def is_real_exam(filename):
    """ข้อสอบจริง = ทุกไฟล์ที่ไม่ได้ขึ้นต้นด้วย chap- / gen-chap-
    ผูกกับ 'ไฟล์' ไม่ใช่ 'รหัสข้อ' — ไม่งั้นข้อสอบจริงข้อใหม่จะแดงทั้งที่ถูก"""
    return not os.path.basename(filename).startswith(('chap-', 'gen-chap-'))


def walk_paths(v, path='$'):
    """เดินทุกสตริงในโครงสร้าง พร้อม "เส้นทางเต็ม" ที่ไปถึงมัน — ลง dict ด้วย

    🔴 บั๊กเดิม (v1) อยู่ตรงนี้: v เป็น dict แล้วไม่ทำอะไรต่อ ⇒ imageSpec ไม่เคยถูกตรวจ
    🔴 เส้นทางคือส่วนที่ v2.6 ไม่มี และเป็นสาเหตุที่ 197 จุดหายเงียบตอนตัดซ้ำ:
       explanation เป็นลิสต์ของขั้นตอน — สองขั้นที่ขึ้นต้นเหมือนกันจะให้
       (โทเคนเดียวกัน, ออฟเซ็ตเดียวกัน) ⇒ ถ้ากุญแจไม่มีเส้นทาง มันคือจุดเดียวกัน
    รูปแบบ: $ · $.imageSpec · $[3] · $.imageSpec.labels[0]
    """
    if isinstance(v, str):
        yield path, v
    elif isinstance(v, list):
        for i, x in enumerate(v):
            yield from walk_paths(x, f'{path}[{i}]')
    elif isinstance(v, dict):
        for k, x in v.items():
            yield from walk_paths(x, f'{path}.{k}')


def walk(v):
    """สตริงล้วน ๆ — เป็น "เปลือกบาง ๆ" ของ walk_paths โดยตั้งใจ

    🔴 ทำไมต้องเป็นเปลือก ไม่ใช่ฟังก์ชันคู่ขนานอีกตัว (กับดัก ⑨):
       ชั้นนับ (scan_question) กับชั้นจุด (enum_points) ต้องเห็น "สตริงชุดเดียวกัน"
       ถ้าเขียนสองตัวแยกกัน วันหนึ่งจะมีคนแก้ตัวหนึ่งแล้วลืมอีกตัว แล้วเลขสองชั้น
       จะต่างกันโดยไม่มีใครรู้ว่าอันไหนถูก ⇒ ผูกให้เป็นตัวหารเดียวกัน "โดยโครงสร้าง"
    ⛔ ห้ามเขียนลูปเดินโครงสร้างเองซ้ำที่อื่นในไฟล์นี้ — เรียกสองตัวนี้เท่านั้น
    """
    for _path, s in walk_paths(v):
        yield s


def scan_question(q, filename):
    """คืนลิสต์ของ (ระดับ, สัญลักษณ์, ฟิลด์, จำนวน) ที่พบ — ระดับดิบ ยังไม่คิดเรื่อง diff"""
    found = []
    realexam = is_real_exam(filename)

    for field, val in q.items():
        if field in FIELDS_NEVER_TOUCH:
            continue
        strings = list(walk(val))
        if not strings:
            continue

        for sym in UNICODE_BANNED + MACRO_BANNED:
            n = sum(s.count(sym) for s in strings)
            if n:
                found.append(('BLOCK', sym, field, n))

        if not realexam:
            for sym in MACRO_REALEXAM_ONLY:
                n = sum(s.count(sym) for s in strings)
                if n:
                    found.append(('BLOCK', sym, field, n))

        # ── ชั้น (ค) กฎเหล็กข้อ 10 · escape เกินชั้น  🆕 v2.8
        #    ⛔ ไม่มีข้อยกเว้น realexam — เป็นความผิด "ตอนพิมพ์เข้าคลัง"
        #       ⛔ ไม่ใช่สัญกรณ์ของต้นฉบับ ⇒ แก้ได้โดยไม่แตะเนื้อโจทย์
        #    ⛔ ไม่แบ่งชั้นตามฟิลด์ — เด็กเห็น \\ ทั้งในโจทย์และในเฉลย
        for sym in ESCAPE_BANNED:
            n = sum(s.count(sym) for s in strings)
            if n:
                found.append(('ESC', sym, field, n))

        # ── ชั้น (ข) ถ้อยคำที่เลิกใช้แล้ว — ห้ามทุกฟิลด์ ทุกไฟล์ รวมข้อสอบจริง
        #    (มติ 1 · E→MB #02 อนุญาตให้แปลง cosec → \csc ในข้อสอบจริงด้วย
        #     ⇒ ที่นี่จึง ⛔ ไม่มีข้อยกเว้น realexam เหมือน MACRO_REALEXAM_ONLY)
        for _w, _rx in WORD_RE.items():
            n = sum(len(_rx.findall(s)) for s in strings)
            if n:
                found.append(('BLOCK', _w, field, n))

        # 🔴 กลบไวต์ลิสต์ "ก่อนนับชั้น TIERED เท่านั้น"
        #    ของต้องห้ามข้างบนนับจาก strings ตัวจริงไปแล้ว ⇒ ไม่มีทางหลุดตามไปด้วย
        masked = [mask_exempt(s) for s in strings]
        for sym in TIERED:
            n = sum(s.count(sym) for s in masked)
            if not n:
                continue
            if field in STUDENT_NOW:
                found.append(('BLOCK', sym, field, n))
            elif field in STUDENT_LATER:
                found.append(('WARN', sym, field, n))
    return found


