def scan_stub(choice_lists):
    """ตัวช่วยของ selftest — นับตัวหารจากลิสต์ตัวเลือกดิบ ⛔ ไม่แตะดิสก์"""
    divisor = 0
    for ch in choice_lists:
        if isinstance(ch, list) and len(ch) >= 2:
            divisor += 1
    return divisor, {}, {}


