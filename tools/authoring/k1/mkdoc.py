def rubric(q):
    m = re.search(r'rubric F(\d) C(\d) P(\d) T(\d) L(\d) = (\d+)', q['notes'])
    return m.groups()


def traps(q):
    i = [k for k, l in enumerate(q['explanation']) if l.startswith('⚠️ <b>จุดพลาด</b>')][0]
    out = []
    first = q['explanation'][i][len('⚠️ <b>จุดพลาด</b>'):].strip()
    if first:
        out.append(first)
    out += [l for l in q['explanation'][i + 1:] if l.strip()]
    return out


