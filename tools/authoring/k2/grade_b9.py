# -*- coding: utf-8 -*-
"""ให้ระดับความยากตาม rubric (F+C+P+T+L เต็ม 15) · ให้คะแนนก่อน แล้วค่อยอ่านระดับ
⛔ ห้ามเลือกระดับก่อนแล้วย้อนหาคะแนน

บันทึกการออกแบบ: ตอนร่างเคยหมายจะให้ q050 เป็นยากมาก และ q051 เป็นยาก
แต่พอให้คะแนนตามตารางจริงได้ 8 กับ 5 ⇒ ไม่ถึง จึงไม่ดันคะแนน
แต่ไปออกแบบ q053 ใหม่ (จากถามผลต่างของด้าน เปลี่ยนเป็นถามพารามิเตอร์ที่ทำให้เกิดสองรูป)
ซึ่งได้ 12 จริง ก้อนนี้จึงยังมี ยากมาก ตามคำสั่งครู
"""
G = [
 # id     S  F  C  P  T  L   เหตุผลสั้นของมิติที่ชี้ขาด
 ('q050', 2, 2, 2, 1, 3, 0, 'กุญแจ 2 ดอก: เอกลักษณ์ arcsin+arccos=pi/2 แล้วช่วงของ u ไม่สมมาตรรอบจุดยอด ⇒ T=3'),
 ('q051', 2, 2, 1, 0, 2, 0, 'กุญแจ 1 ดอก: ต้องรู้ว่าต้องพับกลับเข้าเรนจ์หลัก ⇒ T=2 · ตัวเลขล้วน ⇒ P=0'),
 ('q052', 1, 2, 1, 0, 2, 0, 'กุญแจ: (x-1)^2>=0 ⇒ อสมการล่างไม่ตัดอะไร และห้ามตัด x=1 ⇒ T=2'),
 ('q053', 2, 3, 2, 2, 3, 2, 'ต้องแปลคำว่าสองรูปเป็น h<a<b เอง ⇒ L=2 · k เป็นพารามิเตอร์ ⇒ P=2 · กันปลายสองข้าง ⇒ T=3'),
 ('q054', 2, 3, 1, 1, 3, 1, 'กุญแจ 2 ดอก: ลากทแยงมุมเอง + ใช้ cos D = -cos B กำจัดมุมที่สอง ⇒ T=3'),
]


def level(F, C, P, T, L):
    tot = F + C + P + T + L
    if tot >= 12 and (T == 3 or (T >= 2 and F == 3)):
        return tot, 'ยากมาก'
    if tot >= 8 and (T >= 2 or C >= 2):
        return tot, 'ยาก'
    if tot >= 3 and T <= 2:
        return tot, 'ปานกลาง'
    if tot <= 2 and T <= 1 and C == 0:
        return tot, 'ง่าย'
    return tot, '⚠️ ไม่เข้าเกณฑ์ใด — ต้องออกแบบใหม่'


print('%-6s %2s %2s %2s %2s %2s %2s  %3s  %-8s %s'
      % ('id', 'S', 'F', 'C', 'P', 'T', 'L', 'รวม', 'ระดับ', 'เหตุผล'))
print('-' * 124)
cnt = {}
for g in G:
    qid, S, F, C, P, T, L, why = g
    tot, lv = level(F, C, P, T, L)
    cnt[lv] = cnt.get(lv, 0) + 1
    print('%-6s %2d %2d %2d %2d %2d %2d  %3d  %-8s %s' % (qid, S, F, C, P, T, L, tot, lv, why))
print('-' * 124)
print('สัดส่วนของก้อน 9 :', cnt)
