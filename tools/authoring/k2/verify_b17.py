"""ด่าน D · ตรวจคำตอบก้อน 17 (q090-q094) ด้วย sympy — ทั้งคำตอบจริงและทางเดินของตัวลวง

กฎเหล็กข้อ 1 : ห้ามเชื่อการคำนวณมือ ทุกค่าในตัวเลือกต้องมาจากการรันจริง
กฎเหล็กข้อ 2 : ตัวลวงทุกตัวต้องคำนวณจาก "ทางเดินที่พลาด" ไม่ใช่เลขใกล้เคียง
"""
from sympy import (symbols, sin, cos, tan, cot, pi, sqrt, simplify, nsimplify,
                   Rational, acos, N, trigsimp, S)

th = symbols('theta', positive=True)
ok = True


def chk(tag, got, want, note=''):
    global ok
    d = simplify(got - want)
    good = (d == 0)
    ok = ok and good
    print('%s %-52s = %-22s %s' % ('✅' if good else '❌', tag, want, note))
    if not good:
        print('     ⛔ ได้ %s (ต่าง %s)' % (got, d))


def val(tag, e):
    print('   %-46s ≈ %s' % (tag, N(e, 8)))


print('═══ q090 · cos^2 15 - sin^2 15 ═══')
a = pi / 12                      # 15 องศา
chk('cos^2 15 - sin^2 15', cos(a)**2 - sin(a)**2, sqrt(3) / 2, '= cos 30')
chk('ตัวลวง : จำเป็น cos^2 + sin^2', cos(a)**2 + sin(a)**2, S(1), 'ลืมว่าเป็นลบ')
chk('ตัวลวง : ยุบถูกแต่หยิบ sin 30', sin(2 * a), Rational(1, 2), 'สลับ cos กับ sin หลังยุบ')
chk('ตัวลวง : กลับเป็น sin^2 - cos^2', sin(a)**2 - cos(a)**2, -sqrt(3) / 2, 'สลับที่ตัวตั้งกับตัวลบ')
print('   เรียงจากน้อยไปมาก : -√3/2 , 1/2 , √3/2 , 1  ⇒ คำตอบอยู่ช่อง 3 (correct=2)')

print()
print('═══ q091 · (sin^3 + sin cos^2)/(cos^3 + cos sin^2) ═══')
E = (sin(th)**3 + sin(th) * cos(th)**2) / (cos(th)**3 + cos(th) * sin(th)**2)
chk('ค่านิพจน์', trigsimp(E), tan(th), 'ดึงตัวประกอบร่วมแล้วใช้ sin^2+cos^2 = 1')
# ทางเดินของตัวลวง
chk('ตัวลวง : ตัดพจน์ที่สองของเศษ-ส่วนทิ้งคู่กัน',
    trigsimp(sin(th)**3 / cos(th)**3), tan(th)**3, 'เหลือ sin^3/cos^3')
chk('พิสูจน์ว่าพจน์ที่สองตัดกันไม่ได้จริง',
    trigsimp(sin(th) * cos(th)**2 / (cos(th) * sin(th)**2)), cot(th), '⇒ ไม่ใช่ 1 · ตัดทิ้งคือความผิด')
chk('ตัวลวง : เขียน tan กลับหัวเป็น cos/sin',
    trigsimp(cos(th) / sin(th)), cot(th), 'สลับนิยาม tan')
print('   ตัวลวง 1 : ตัดวงเล็บพร้อม sin กับ cos หน้าออกหมด ⇒ 1')
print('   เรียง ค่าคงที่ → ฟังก์ชันเดี่ยวตามชื่อ → กำลังสูงขึ้น : 1 , cot , tan , tan^3 ⇒ ช่อง 3 (correct=2)')

print()
print('═══ q092 · ถังทรงกระบอกนอนราบ r=2 ยาว 6 น้ำลึก 1 ═══')
r, L, d = S(2), S(6), S(1)
half = acos((r - d) / r)          # ครึ่งหนึ่งของมุมที่จุดศูนย์กลาง
cen = 2 * half
chk('ครึ่งมุมที่จุดศูนย์กลาง', half, pi / 3, 'cos(θ/2) = (r-d)/r = 1/2')
chk('มุมที่จุดศูนย์กลาง', cen, 2 * pi / 3, '= 120 องศา')
seg = r**2 / 2 * (cen - sin(cen))
chk('พื้นที่หน้าตัดของน้ำ (เซกเมนต์)', seg, 4 * pi / 3 - sqrt(3), '½r²(θ - sin θ)')
V = seg * L
chk('ปริมาตรน้ำ', V, 8 * pi - 6 * sqrt(3), '× ความยาวถัง')
val('ปริมาตรน้ำ', V)
# ตัวลวง
d1 = (r**2 / 2 * cen) * L
chk('ตัวลวง : เอาแต่เซกเตอร์ ลืมลบสามเหลี่ยม', d1, 8 * pi, '')
val('8π', d1)
d2 = (r**2 / 2 * (pi / 3 - sin(pi / 3))) * L
chk('ตัวลวง : ใช้ครึ่งมุม π/3 เป็นมุมที่จุดศูนย์กลาง', d2, 4 * pi - 6 * sqrt(3), '')
val('4π - 6√3', d2)
d3 = pi * r**2 * L / 4
chk('ตัวลวง : เห็นลึก 1 จาก 4 ⇒ คิดเป็นหนึ่งในสี่ของถัง', d3, 6 * pi, '')
val('6π', d3)
print('   เรียงจากน้อยไปมาก : 4π-6√3 , 8π-6√3 , 6π , 8π ⇒ คำตอบอยู่ช่อง 2 (correct=1)')

print()
print('═══ q093 · เสาสูง 20 ที่เชิงลาด 15 องศา แดด 60 องศา ⇒ เงาทอดขึ้นลาด ═══')
h = S(20)
al, be = pi / 3, pi / 12          # แดด 60 · ลาด 15
angB = pi / 2 + be                # มุมที่โคนเสา
angS = al - be                    # มุมที่ปลายเงา
angT = pi - angB - angS           # มุมที่ยอดเสา
chk('มุมที่โคนเสา', angB, 7 * pi / 12, '= 105 องศา')
chk('มุมที่ปลายเงา', angS, pi / 4, '= 45 องศา')
chk('มุมที่ยอดเสา', angT, pi / 6, '= 30 องศา')
BSlen = h * sin(angT) / sin(angS)
chk('ความยาวเงาบนพื้นลาด', simplify(BSlen), 10 * sqrt(2), 'กฎของไซน์')
val('10√2', BSlen)
e1 = h / tan(al)
chk('ตัวลวง : ลืมว่าพื้นลาด ใช้ h/tan 60', simplify(e1), 20 * sqrt(3) / 3, '')
val('20√3/3', e1)
e2 = h * sin(pi / 6) / sin(al + be)
chk('ตัวลวง : บวกมุมแทนที่จะลบ ⇒ ใช้ sin 75', simplify(e2), 10 * (sqrt(6) - sqrt(2)), '')
val('10(√6-√2)', e2)
e3 = h * sin(al) / sin(angS)
chk('ตัวลวง : ลอกมุมเงย 60 มาใช้เป็นมุมที่ยอดเสา', simplify(e3), 10 * sqrt(6), '')
val('10√6', e3)
print('   เรียงจากน้อยไปมาก : 10(√6-√2) , 20√3/3 , 10√2 , 10√6 ⇒ คำตอบอยู่ช่อง 3 (correct=2)')

print()
print('═══ q094 · ม้วนเซกเตอร์ R=12 มุม 120 องศา เป็นกรวย ⇒ ปริมาตร ═══')
R, cen2 = S(12), 2 * pi / 3
arc = R * cen2
chk('ความยาวส่วนโค้ง', arc, 8 * pi, 'Rθ')
rb = arc / (2 * pi)
chk('รัศมีฐานกรวย', rb, S(4), 'ส่วนโค้ง = เส้นรอบวงฐาน')
hh = sqrt(R**2 - rb**2)
chk('ความสูงกรวย', hh, 8 * sqrt(2), 'พีทาโกรัส (R คือสูงเอียง)')
V2 = pi * rb**2 * hh / 3
chk('ปริมาตรกรวย', simplify(V2), 128 * sqrt(2) * pi / 3, '')
val('128√2π/3', V2)
f1 = pi * rb**2 * R / 3
chk('ตัวลวง : ใช้ R เป็นความสูง (ลืมว่าเป็นสูงเอียง)', f1, 64 * pi, '')
val('64π', f1)
f2 = pi * rb**2 * hh
chk('ตัวลวง : ลืมคูณหนึ่งส่วนสาม', simplify(f2), 128 * sqrt(2) * pi, '')
val('128√2π', f2)
rbad = arc / pi
f3 = pi * rbad**2 * sqrt(R**2 - rbad**2) / 3
chk('ตัวลวง : ลืมหารด้วย 2 ⇒ รัศมีฐาน 8', simplify(f3), 256 * sqrt(5) * pi / 3, '')
val('256√5π/3', f3)
print('   เรียงจากน้อยไปมาก : 128√2π/3 , 64π , 128√2π , 256√5π/3 ⇒ คำตอบอยู่ช่อง 1 (correct=0)')

print()
print('═' * 70)
print('ผลรวมด่าน D :', 'ผ่านทุกบรรทัด ✅' if ok else 'มีบรรทัดตก ❌')
