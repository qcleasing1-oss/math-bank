"""ให้ระดับความยากตาม rubric (F+C+P+T+L เต็ม 15) · ให้คะแนนก่อน แล้วค่อยอ่านระดับ
⛔ ห้ามเลือกระดับก่อนแล้วย้อนหาคะแนน"""
G = [
 # id     S  F  C  P  T  L   เหตุผลสั้นของมิติที่ชี้ขาด
 ('q045', 1, 1, 1, 2, 1, 0, 'ตารางเครื่องหมายตรง ๆ ก็ทำได้ ⇒ T=1 · ถามคุณสมบัติไม่ใช่ค่า ⇒ P=2'),
 ('q046', 2, 3, 2, 0, 3, 1, 'กุญแจ 2 ดอก: tan·cot=1 และ หารด้วย sin ที่อยู่ใน (0,1) ⇒ T=3'),
 ('q047', 2, 3, 2, 2, 3, 2, 'ต้องสร้างแบบจำลองเอง ⇒ P=2 · กุญแจ 2 ดอก (ตั้งอสมการ + 15 ไม่ครบรอบ) ⇒ T=3'),
 ('q048', 1, 2, 1, 1, 2, 0, 'แก้ที่ตัวในวงเล็บ + จำช่วงเพิ่มของ cos ให้ถูก ⇒ T=2'),
 ('q049', 2, 2, 1, 2, 2, 0, 'b เป็นพารามิเตอร์จากเงื่อนไขคุณสมบัติ ⇒ P=2 · กุญแจ: จำนวนจุดตัด = b ⇒ T=2'),
]


def level(F, C, P, T, L):
    tot = F + C + P + T + L
    if tot >= 12 and (T == 3 or (T >= 2 and F == 3)):
        return tot, 'ยากมาก'
    if tot >= 8 and (T >= 2 or C >= 2):
        return tot, 'ยาก'
    if tot >= 3 and T <= 2:
        return tot, 'ปานกลาง'
    if tot <= 2 and T <= 1 and C == 0:
        return tot, 'ง่าย'
    return tot, '⚠️ ไม่เข้าเกณฑ์ใด — ต้องออกแบบใหม่'


print('%-6s %2s %2s %2s %2s %2s %2s  %3s  %-8s %s'
      % ('id', 'S', 'F', 'C', 'P', 'T', 'L', 'รวม', 'ระดับ', 'เหตุผล'))
print('-' * 116)
cnt = {}
for qid, S, F, C, P, T, L in [(g[0],) + g[1:7] for g in G]:
    tot, lv = level(F, C, P, T, L)
    why = [g[7] for g in G if g[0] == qid][0]
    cnt[lv] = cnt.get(lv, 0) + 1
    print('%-6s %2d %2d %2d %2d %2d %2d  %3d  %-8s %s' % (qid, S, F, C, P, T, L, tot, lv, why))
print('-' * 116)
print('สัดส่วนของก้อน 8 :', cnt)
