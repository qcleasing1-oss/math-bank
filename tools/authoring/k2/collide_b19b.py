import io, json, glob, re

items, seen = [], set()
for p in sorted(glob.glob('/tmp/mb27/data/sets/*.json') +
                glob.glob('/home/claude/k1/out/*.json') +
                glob.glob('/home/claude/k2/out/*.json')):
    d = json.load(io.open(p, encoding='utf-8'))
    for q in d.get('questions', []):
        if q['id'] in seen:
            continue
        seen.add(q['id'])
        q['_src'] = p.split('/')[-1].replace('.json', '')
        items.append(q)
print('ฐานเทียบ %d ข้อ' % len(items))


def andscan(label, pats, sub=None, show=8):
    rxs = [re.compile(p) for p in pats]
    hit = []
    for q in items:
        s = q.get('question') or ''
        if sub and not (set(q.get('subTopics') or []) & set(sub)):
            continue
        if all(r.search(s) for r in rxs):
            hit.append(q)
    print()
    print('== %s ==  %d ข้อ' % (label, len(hit)))
    for q in hit[:show]:
        print('   %-34s %-8s %-10s %s' % (q['id'], q.get('difficulty', '?'),
              '/'.join(q.get('subTopics') or []), (q.get('question') or '').replace('\n', ' ')[:100]))
    if len(hit) > show:
        print('   ... อีก %d' % (len(hit) - show))
    return hit


