def level(F, C, P, T, L):
    tot = F + C + P + T + L
    if tot >= 12 and (T == 3 or (T >= 2 and F == 3)):
        return tot, 'ยากมาก'
    if tot >= 8 and (T >= 2 or C >= 2):
        return tot, 'ยาก'
    if tot >= 3 and T <= 2:
        return tot, 'ปานกลาง'
    if tot <= 2 and T <= 1 and C == 0:
        return tot, 'ง่าย'
    return tot, '⚠️ ไม่เข้าเกณฑ์ใด — ต้องออกแบบใหม่'


