def split_expl(ex):
    """แยก explanation เดิมเป็น (หัวร่วม, ตัวแบบที่1, หาง)

    🔴 ข้อสำคัญ : 8 ข้อในก้อนนี้มีหัว 【 】 สองอันอยู่แล้ว (วิธีที่ 1 + วิธีที่ 2 ⚡)
    แบบที่ 1 ของสเปกใหม่ = **บล็อกแรกเท่านั้น** บล็อกที่สองถูกแทนที่ด้วยแบบที่ 3 ที่เขียนใหม่
    ⛔ ถ้าตัดที่หัวแรกอย่างเดียว ผู้เขียนจะเห็นวิธีที่สองปนมาแล้วเข้าใจผิดว่าแบบที่ 1 คือทั้งสองวิธี
    """
    heads = [i for i, l in enumerate(ex) if l.startswith('<b>【')]
    i_tail = next(i for i, l in enumerate(ex) if l.startswith('✔ <b>ตรวจคำตอบ'))
    i_end = heads[1] if len(heads) > 1 else i_tail
    return ex[:heads[0]], ex[heads[0]:i_end], ex[i_tail:]


