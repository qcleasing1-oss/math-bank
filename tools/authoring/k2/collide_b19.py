import io, json, glob, re

items = []
for p in sorted(glob.glob('/tmp/mb27/data/sets/*.json') +
                glob.glob('/home/claude/k1/out/*.json') +
                glob.glob('/home/claude/k2/out/*.json')):
    d = json.load(io.open(p, encoding='utf-8'))
    for q in d.get('questions', []):
        q['_src'] = p.split('/')[-1].replace('.json', '')
        items.append(q)

seen = set()
uniq = []
for q in items:
    if q['id'] in seen:
        continue
    seen.add(q['id'])
    uniq.append(q)
items = uniq
print('ฐานเทียบ %d ข้อ (ตัด id ซ้ำแล้ว)' % len(items))


def txt(q):
    parts = [q.get('question') or '']
    parts += [str(c) for c in (q.get('choices') or [])]
    ex = q.get('explanation') or ''
    parts += ex if isinstance(ex, list) else [str(ex)]
    return '\n'.join(parts)


def scan(label, pattern, qonly=True, show=6, flags=0):
    rx = re.compile(pattern, flags)
    hit = [q for q in items if rx.search((q.get('question') or '') if qonly else txt(q))]
    print()
    print('== %s ==  %d ข้อ' % (label, len(hit)))
    for q in hit[:show]:
        print('   %-34s %-8s %-10s %s' % (q['id'], q.get('difficulty', '?'),
              '/'.join(q.get('subTopics') or []), (q.get('question') or '').replace('\n', ' ')[:105]))
    if len(hit) > show:
        print('   ... อีก %d' % (len(hit) - show))
    return hit


def both(label, a, b, show=6):
    """ตัดกันของสองโพรบ — ใช้เมื่อคำเดี่ยวกว้างเกินจนอ่านผลไม่ไหว"""
    ra, rb = re.compile(a), re.compile(b)
    hit = [q for q in items
           if ra.search(q.get('question') or '') and rb.search(q.get('question') or '')]
    print()
    print('== %s ==  %d ข้อ' % (label, len(hit)))
    for q in hit[:show]:
        print('   %-34s %-8s %-10s %s' % (q['id'], q.get('difficulty', '?'),
              '/'.join(q.get('subTopics') or []), (q.get('question') or '').replace('\n', ' ')[:105]))
    if len(hit) > show:
        print('   ... อีก %d' % (len(hit) - show))
    return hit


